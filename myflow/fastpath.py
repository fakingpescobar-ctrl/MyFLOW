"""MyFLOW — быстрый путь: когда полировка LLM не нужна.

Идея: GigaAM v3 e2e уже отдаёт текст с пунктуацией, заглавными и нормализацией
чисел, поэтому LLM часто меняет в нём почти ничего (замер на длинной фразе:
divergence 0.05), а стоит 110-180 мс — то есть дороже самого распознавания.
Если текст уже оформлен, полировку можно не звать и вставить результат ASR как
есть.

Правило намеренно КОНСЕРВАТИВНОЕ: пропускаем только когда
  * в тексте есть конечная пунктуация (.!?…) и он начинается с заглавной;
  * нет слов-паразитов, которые полировка обязана убрать;
  * нет чисел, записанных словами («восемь тысяч восемьдесят один» — правило
    чисел из промпта превратило бы их в 8081);
  * в тексте не меньше 3 слов (совсем короткие фразы полировка всё равно
    оформляет быстрее, чем мы успеваем решить).
Плюс быстрый путь включается только для стиля `plain` (для terminal/style
полировка реально переформатирует текст) и только для бэкенда, который сам
ставит пунктуацию (GigaAM e2e). Для whisper правило не применяется — его вывод
почти всегда идёт без пунктуации и с заглавной только в начале.

Все пропуски видны в истории: `history.status = "fast_path"`, а в статистике —
в `by_status`.
"""
from __future__ import annotations

import re

# Слова-паразиты и обороты, которые полировка обязана убрать: если они есть,
# быстрый путь не применяем (иначе они попадут в текст).
FILLER_MARKERS: tuple[str, ...] = (
    "типа", "как бы", "короче", "эээ", "ээ", "эм-м", "эм", "мм", "э-э",
    "ну это", "вот так вот", "собственно говоря", "так сказать",
    "в общем-то", "в общем", "блин", "значит", "понимаешь", "это самое",
    # Найдено стендом на реальных фразах: «Второе, значит, э-э, насчёт» уходило
    # в быстрый путь с филлерами внутри — полировка их бы убрала.
)

# Числа словами: их полировка переводит в цифры (единственное, что она делает
# заметного на уже оформленном тексте).
NUMBER_WORDS: frozenset[str] = frozenset({
    "ноль", "один", "одна", "одно", "два", "две", "три", "четыре", "пять",
    "шесть", "семь", "восемь", "девять", "десять", "одиннадцать", "двенадцать",
    "тринадцать", "четырнадцать", "пятнадцать", "шестнадцать", "семнадцать",
    "восемнадцать", "девятнадцать", "двадцать", "тридцать", "сорок",
    "пятьдесят", "шестьдесят", "семьдесят", "восемьдесят", "девяносто",
    "сто", "двести", "триста", "четыреста", "пятьсот", "шестьсот", "семьсот",
    "восемьсот", "девятьсот", "тысяча", "тысячи", "тысяч", "миллион",
    "миллиона", "миллионов", "полтора", "полторы",
})

# Короткие слова, которыми фраза может заканчиваться законно; всё остальное
# длиной 1-2 буквы считаем обрывком («по», «ка», «сл»).
_SHORT_WORDS_OK: frozenset[str] = frozenset({
    "и", "в", "во", "не", "на", "то", "же", "бы", "ли", "до", "за", "из", "к",
    "ко", "о", "об", "с", "со", "у", "я", "а", "но", "да", "ну", "мы", "вы",
    "он", "она", "оно", "их", "их", "мне", "тебе", "всё", "все", "это", "как",
    "что", "чем", "там", "тут", "уж", "их", "её", "его", "мы", "ты",
})
_TERMINAL = ".!?…"
_WORD_RE = re.compile(r"[а-яё]+", re.IGNORECASE)
# Дефекты расстановки, которые полировка обычно чинит: «телевизоре..»,
# « ,», двойные пробелы, «,,». Замер: GigaAM e2e выдаёт «телевизоре..»
# (val_tv_2) — такие фразы отправляем в LLM.
_PUNCT_DEFECTS: tuple[str, ...] = ("..", "  ", ",,", " .", " ,", " !", " ?", "?!", "!?")


def looks_wellformed(text: str, min_words: int = 3) -> tuple[bool, str]:
    """Проверить, можно ли вставлять текст ASR без полировки.

    Возвращает (можно_ли, причина). Причина нужна для лога и диагностики:
    видно, ПОЧЕМУ фраза не пошла по быстрому пути.
    """
    t = (text or "").strip()
    if not t:
        return False, "пустой текст"
    words = t.split()
    if len(words) < min_words:
        return False, f"короче {min_words} слов"
    if t[-1] not in _TERMINAL:
        return False, "нет конечной пунктуации"
    if not t[0].isupper():
        return False, "нет заглавной в начале"
    for defect in _PUNCT_DEFECTS:
        if defect in t:
            return False, f"дефект пунктуации {defect!r}"
    low = t.lower()
    for marker in FILLER_MARKERS:
        if marker in low:
            return False, f"слова-паразиты «{marker}»"
    number_hits = {w for w in _WORD_RE.findall(low) if w in NUMBER_WORDS}
    if number_hits:
        return False, "числа словами: " + ", ".join(sorted(number_hits)[:3])
    # Обрывок в конце: GigaAM иногда режет слово и всё равно ставит точку
    # («А что быы ты по.»). Короткий последний токен вне списка частых слов —
    # признак обрыва: такую фразу отдаём полировке, она хвост уберёт.
    last = _WORD_RE.findall(low)[-1] if _WORD_RE.findall(low) else ""
    if 0 < len(last) <= 2 and last not in _SHORT_WORDS_OK:
        return False, f"подозрительный обрывок в конце: «{last}»"
    return True, "текст уже оформлен"


def fast_path_allowed(asr_backend: str, style: str, text: str) -> tuple[bool, str]:
    """Полное решение: бэкенд + стиль + текст.

    Быстрый путь имеет смысл только для бэкендов, которые сами расставляют
    пунктуацию и заглавные (GigaAM e2e); whisper-текст через него не пускаем.
    """
    backend = (asr_backend or "").lower()
    if "gigaam" not in backend:
        return False, "бэкенд ASR без пунктуации (нужен GigaAM e2e)"
    if style != "plain":
        return False, f"стиль «{style}» переформатирует текст"
    return looks_wellformed(text)
